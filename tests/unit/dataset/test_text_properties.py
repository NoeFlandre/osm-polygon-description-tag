"""Properties of the shared text contract, and its SQL twin run through DuckDB."""

from __future__ import annotations

import duckdb
import pyarrow as pa
from hypothesis import example, given
from hypothesis import strategies as st

from osm_polygon_description_tag.dataset.text import (
    description_row_has_successful_text,
    is_nonempty_text,
    is_trimmed_nonempty_text,
    successful_description_text_sql,
    trimmed_nonempty_text,
)

# Code points around Python's str.strip: what it removes, and look-alikes it keeps.
_ODD = "".join(
    map(
        chr,
        [
            *(9, 10, 11, 12, 13, 28, 29, 30, 31, 32, 0x85, 0xA0, 0x1680),
            *(0x2000, 0x2003, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0x200B, 0xFEFF),
        ],
    )
)
_TEXTS = st.text(
    alphabet=st.one_of(st.sampled_from(_ODD), st.characters(codec="utf-8")), max_size=12
)
_ANYTHING = st.one_of(_TEXTS, st.none(), st.integers(), st.binary(max_size=4), st.lists(_TEXTS))


@given(_ANYTHING)
@example("")
@example("  " + chr(0xA0) + " ")
@example(" x ")
def test_trimming_is_idempotent_and_yields_none_or_stripped_text(value: object) -> None:
    once = trimmed_nonempty_text(value)

    assert trimmed_nonempty_text(once) == once
    if once is not None:
        assert once == once.strip()
        assert once


@given(_ANYTHING)
def test_a_value_is_usable_exactly_when_it_is_text_with_content(value: object) -> None:
    usable = trimmed_nonempty_text(value) is not None

    assert usable == (isinstance(value, str) and bool(value.strip()))
    assert is_nonempty_text(value) == usable


@given(_ANYTHING)
def test_canonical_text_is_exactly_the_text_that_trimming_leaves_unchanged(value: object) -> None:
    assert is_trimmed_nonempty_text(value) == (
        isinstance(value, str) and trimmed_nonempty_text(value) == value
    )
    if is_trimmed_nonempty_text(value):
        assert is_nonempty_text(value)


_LOCALIZED = st.one_of(
    st.none(),
    st.lists(
        st.fixed_dictionaries(
            {"key": st.sampled_from(["en", "fr", "de"]), "value": st.one_of(_TEXTS, st.none())}
        ),
        max_size=3,
    ),
)
_CONNECTION = duckdb.connect()
_SQL = successful_description_text_sql(localized_is_map=False)


_LOCALIZED_TYPE = pa.list_(pa.struct([("key", pa.string()), ("value", pa.string())]))


def _sql_verdict(description: str | None, localized: list[dict[str, str | None]] | None) -> bool:
    table = pa.table(
        {
            "description": pa.array([description], type=pa.string()),
            "localized_descriptions": pa.array([localized], type=_LOCALIZED_TYPE),
        }
    )
    _CONNECTION.register("rows", table)
    try:
        row = _CONNECTION.execute(f"SELECT {_SQL} FROM rows").fetchone()  # noqa: S608 - generated by the tested helper
    finally:
        _CONNECTION.unregister("rows")
    assert row is not None
    return bool(row[0])


@given(st.one_of(_TEXTS, st.none()), _LOCALIZED)
@example("valid", [{"key": "en", "value": "valid"}, {"key": "fr", "value": " padded "}])
@example(None, [])
@example(None, None)
def test_the_python_and_sql_text_predicates_agree(
    description: str | None, localized: list[dict[str, str | None]] | None
) -> None:
    row = {"description": description, "localized_descriptions": localized}

    assert _sql_verdict(description, localized) == description_row_has_successful_text(row)
