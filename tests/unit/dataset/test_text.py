from __future__ import annotations

import duckdb
import pytest

from osm_polygon_description_tag.dataset.text import (
    _localized_values,
    _sql_literal,
    _valid_localized_values,
    description_row_has_successful_text,
    has_successful_description_text,
    successful_description_text_sql,
    trimmed_nonempty_text,
)


@pytest.mark.parametrize(
    ("value", "expected"),
    [(None, None), ("", None), (" \t", None), ("  text \n", "text")],
)
def test_trimmed_nonempty_text_is_the_shared_value_normalizer(
    value: object, expected: str | None
) -> None:
    assert trimmed_nonempty_text(value) == expected


@pytest.mark.parametrize(
    ("description", "localized", "expected"),
    [
        (None, [], False),
        (" ", [], False),
        ("text", [], True),
        (None, [{"key": "en", "value": "text"}], True),
        ("text", [{"key": "en", "value": "text"}], True),
        (None, [{"key": "en", "value": " "}], False),
        (None, [{"key": "en", "value": " text "}], False),
        ("text", ["malformed"], False),
    ],
)
def test_successful_description_text_rejects_invalid_row_values(
    description: object, localized: object, expected: bool
) -> None:
    assert has_successful_description_text(description, localized) is expected
    assert (
        description_row_has_successful_text(
            {"description": description, "localized_descriptions": localized}
        )
        is expected
    )


def test_successful_description_text_rejects_malformed_localized_values_with_valid_base() -> None:
    assert has_successful_description_text("valid", 42) is False


def test_sql_text_boundary_rejects_invalid_localized_sibling_with_valid_base() -> None:
    expression = successful_description_text_sql(localized_is_map=False)
    connection = duckdb.connect()
    try:
        accepted = connection.execute(
            "SELECT "  # noqa: S608 - expression is generated by the tested helper
            f"{expression} "
            "FROM (SELECT 'valid'::VARCHAR AS description, "
            "[{'key': 'en', 'value': 'valid'}, "
            "{'key': 'fr', 'value': ' padded '}]::STRUCT(key VARCHAR, value VARCHAR)[] "
            "AS localized_descriptions)",
        ).fetchone()[0]
    finally:
        connection.close()

    assert accepted is False


def test_localized_value_helpers_reject_non_sequence_values() -> None:
    assert _localized_values(42) is None
    assert _valid_localized_values(42) is None


def test_description_row_predicate_forwards_both_text_columns() -> None:
    row = {"description": None, "localized_descriptions": [{"key": "en", "value": "valid"}]}

    assert description_row_has_successful_text(row) is True


def test_sql_literal_escapes_apostrophes() -> None:
    assert _sql_literal("L'auteur") == "'L''auteur'"


def test_successful_description_text_sql_requires_trimmed_nonempty_values() -> None:
    expression = successful_description_text_sql(localized_is_map=True)

    assert "length(description) > 0" in expression
    assert "description = trim(description," in expression
    assert "entry.value = trim(entry.value," in expression
    assert "map_entries(localized_descriptions)" in expression
    assert "WHERE entry.value IS NOT NULL " in expression
    assert "AND length(entry.value) > 0 " in expression
    assert "AND entry.value = trim(entry.value," in expression


@pytest.mark.parametrize("value", ["\ttext\n", "\u2003text\u2003", "\u00a0text\u00a0"])
def test_sql_text_boundary_matches_python_for_unicode_whitespace(value: str) -> None:
    expression = successful_description_text_sql(localized_is_map=False)
    connection = duckdb.connect()
    try:
        accepted = connection.execute(
            "SELECT "  # noqa: S608 - expression is generated by the tested helper
            f"{expression} "
            "FROM (SELECT ?::VARCHAR AS description, "
            "[]::STRUCT(key VARCHAR, value VARCHAR)[] AS localized_descriptions)",
            [value],
        ).fetchone()[0]
    finally:
        connection.close()

    assert accepted is has_successful_description_text(value, [])
